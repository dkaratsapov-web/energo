"""
Развороты 8–9, 10–11, 12–13, 14–15 — серия «направление работ + объект».

В утверждённом каталоге это четыре одинаково устроенные пары: слева плашка
с названием направления и перечнем работ, справа фотографии объекта. Пара
задана структурой издания; новая вёрстка её наконец использует.

Общая композиция серии:
  · левая полоса — текст: надзаголовок, название направления, перечень
    работ, а внизу кадр объекта полосой навылет;
  · правая полоса — два кадра во всю полосу навылет, один над другим.

Кадр держит полосу. В утверждённом каталоге фотография шла навылет, и
объект было видно; столбец мелких кадров объект не показывает — это и была
главная претензия к первой сборке новой вёрстки.

Цена размера — разрешение. Полосы утверждённого каталога сведены в растр
1240 px по ширине; кадр во всю полосу печатается из них примерно в 150 dpi,
кадр на нижней полосе левой страницы — около 164. Это ниже типографской
нормы 300 dpi, и исправляется только оригиналами съёмки: интерполяция даёт
формальные 300 dpi, но резкости не прибавляет. Фактическое разрешение
каждого кадра печатает scripts/qa_images.py — цифры не прячутся.

Тон чередуется: 8–9 тёмный, 10–11 светлый, 12–13 тёмный, 14–15 светлый.
"""
