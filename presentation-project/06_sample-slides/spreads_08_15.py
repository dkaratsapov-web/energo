"""
Развороты 8–9, 10–11, 12–13, 14–15 — серия «направление работ + объект».

В утверждённом каталоге это четыре одинаково устроенные пары: слева плашка
с названием направления и перечнем работ, справа фотографии объекта. Пара
задана структурой издания; новая вёрстка её наконец использует.

Общая композиция серии:
  · левая полоса — текст: надзаголовок, название направления, перечень работ
    по общей сетке отбивок, набор доведён до нижнего поля;
  · правая полоса — три кадра одинаковой ширины, прижатые к ВНЕШНЕМУ обрезу
    и поставленные столбцом;
  · воздух собран у сгиба: пустая колонка шириной 67 мм идёт вдоль корешка,
    то есть ровно там, где разворот и так уходит в глубину.

Размер кадра — не вкусовое решение. Полосы утверждённого каталога сведены в
растр 1240 px по ширине, то есть 150 dpi на A4; именно из-за этого прежний
файл и завернули. Кадр шириной 105 мм печатается из тех же 1240 px в 300 dpi.
Поэтому фотография здесь никогда не идёт навылет через разворот: она стоит
кадром расчётного размера, и каждый кадр проверяется по готовому PDF
(scripts/qa_images.py). Придут оригиналы съёмки — вёрстка возьмёт их без
переделки, предел считается из пикселей файла.

Тон чередуется: 8–9 тёмный, 10–11 светлый, 12–13 тёмный, 14–15 светлый.
"""
