def service(s, n, num, section_l, section_r, title, items, photos,
            dark=True, item_size=12, step=20*mm, lead=1.40):
    """Разворот серии «направление работ»."""
    # Фон, шапка и колонцифры — общая схема каталога (scripts/layouts.py):
    # одна реализация на все развороты, иначе они расходятся по мелочам.
    t = base(s, n, section_l, section_r, dark=dark, seed=n)
    line, muted, ghost = t.line, t.muted, t.ghost
    # ── левая полоса: направление и перечень работ ───────────────────────
    xl, wl = px(L, 0, 12)
    s.eyebrow(L, f'НАПРАВЛЕНИЕ {num} ИЗ 10')
    yb = s.title(L, title, dark=dark)

    # Перечень идёт от общей для серии горизонтали, но у длинного названия
    # (четыре строки на 14–15) отступает от его последней строки.
    y = min(200*mm, yb - 20*mm)
    for i, it in enumerate(items, 1):
        s.rule(xl, y + 11*mm, wl, line, 0.5)
        s.numbered(i, xl, y, it, dark=dark, size=item_size, num_w=13*mm,
                   width=wl, lead=lead)
        y -= step
    s.rule(xl, y + 11*mm, wl, line, 0.5)

    # ── кадры ───────────────────────────────────────────────────────────
    # Правая полоса — два кадра во всю полосу: пропорция 214×151 мм почти
    # точно совпадает с пропорцией исходников, кадры встают без обрезки.
    photo_rows(s, R, [p[0] for p in photos[:2]], PAGE_H + BLEED, -BLEED)
    # Третий кадр — полосой у нижнего обреза левой страницы, от корешкового
    # поля до внешнего вылета. Разворот читается по диагонали.
    if len(photos) > 2:
        full_photo(s, L, photos[2][0], -BLEED, 100*mm,
                   x1=PAGE_W - MARGIN_INNER)



def pair_band(s, side, a, b, y0, y1, x1, gap=3*mm):
    """Два кадра рядом одной полосой у нижнего обреза — когда исходники
    вдвое уже остальных и во всю полосу дали бы 82 dpi."""
    x0, _ = s.bleed_box(side)
    w = (x1 - x0 - gap)/2
    s.photo(f'{PH}/{a}.png', x0,          y0, w, y1 - y0)
    s.photo(f'{PH}/{b}.png', x0 + w + gap, y0, w, y1 - y0)


