# Столбец кадров у внешнего обреза правой полосы. Ширина 105 мм — предел,
# при котором исходные 1240 px дают ровно 300 dpi. Высота каждого кадра
# считается из его собственных пикселей: у четырёх кадров серии срезан верх
# с впечатанным логотипом, и они ниже остальных. Остаток высоты уходит в
# равные промежутки, поэтому столбец всегда стоит от верха до нижнего поля.
PW      = 105*mm
PX      = SPREAD_W - MARGIN_OUTER - PW
COL_TOP, COL_BOT, GAP_MAX = 244*mm, MARGIN_BOTTOM, 14*mm


def column(photos, dpi=300):
    """Кадры столбцом: высота каждого — предел его разрешения, не вкус.

    Запись вида (None, высота) резервирует слот под кадр, который рисуется
    отдельно, — так в столбец встаёт пара узких кадров.
    """
    import cv2
    hs = []
    for path, a_ in photos:
        if path is None:
            hs.append(a_); continue
        a = cv2.imread(f'{PH}/{path}.png')
        hs.append(min(a.shape[0]/dpi*25.4*mm, PW*a.shape[0]/a.shape[1]))
    gap = min(GAP_MAX, (COL_TOP - COL_BOT - sum(hs))/max(len(hs) - 1, 1))
    y = COL_TOP
    out = []
    for (path, anchor), h in zip(photos, hs):
        y -= h
        out.append((path, anchor, y, h))
        y -= gap
    return out

def service(s, n, num, section_l, section_r, title, items, photos,
            dark=True, item_size=12, step=20*mm, lead=1.40):
    """Разворот серии «направление работ»."""
    # Фон, шапка и колонцифры — общая схема каталога (scripts/layouts.py):
    # одна реализация на все развороты, иначе они расходятся по мелочам.
    t = base(s, n, section_l, section_r, dark=dark, seed=n)
    line, muted, ghost = t.line, t.muted, t.ghost
    # ── левая полоса: направление и перечень работ ───────────────────────
    xl, wl = px(L, 0, 12)
    s.eyebrow(L, f'НАПРАВЛЕНИЕ {num} ИЗ 10')
    yb = s.title(L, title, dark=dark)

    # Номер направления крупно у нижнего поля. Он не добавляет текста —
    # то же число стоит в надзаголовке, — но закрывает низ полосы и даёт
    # серии из четырёх разворотов узнаваемый ритм: иначе под коротким
    # перечнем остаётся дыра в треть полосы.
    # Базовая линия поднята над колонцифрой: у кегля 200 pt метрический
    # габарит строки уходит на 17 мм ниже базовой линии, и при посадке
    # на нижнее поле он перекрыл бы колонцифру.
    s.text(num, xl, MARGIN_BOTTOM + 24*mm, T.FONT_BLACK, 200, ghost, track=-30)

    # Перечень идёт от общей для серии горизонтали, но у длинного названия
    # (четыре строки на 14–15) отступает от его последней строки.
    y = min(200*mm, yb - 20*mm)
    for i, it in enumerate(items, 1):
        s.rule(xl, y + 11*mm, wl, line, 0.5)
        s.numbered(i, xl, y, it, dark=dark, size=item_size, num_w=13*mm,
                   width=wl, lead=lead)
        y -= step
    s.rule(xl, y + 11*mm, wl, line, 0.5)

    # ── правая полоса: кадры столбцом у внешнего обреза ──────────────────
    for path, anchor, y, h in column(photos):
        if path is not None:
            s.photo(f'{PH}/{path}.png', PX, y, PW, h, anchor=anchor)


def pair(s, path_a, path_b, y, h, anchor='c'):
    """Два кадра рядом в одном слоте — когда исходник вдвое уже остальных."""
    w = (PW - 4*mm)/2
    s.photo(f'{PH}/{path_a}.png', PX,            y, w, h, anchor=anchor)
    s.photo(f'{PH}/{path_b}.png', PX + w + 4*mm, y, w, h, anchor=anchor)


