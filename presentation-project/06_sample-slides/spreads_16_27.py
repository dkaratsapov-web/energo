def spread_26_27(s):
    t = base(s, 26, 'Гражданское строительство', 'Промышленное строительство',
             dark=False, seed=26)

    yb = topic(s, L, 'ЖИЛЫЕ ДОМА', ['ГРАЖДАНСКОЕ', 'СТРОИТЕЛЬСТВО'], t)
