def _growth(s, BH):
    """Динамика портфеля: площадная диаграмма через весь разворот.

    Шаг по оси подобран так, чтобы ни одна точка и ни одна подпись не попали
    в мёртвую зону сгиба: 2022 встаёт вплотную к корешковому полю левой
    полосы, 2023 — сразу за корешковым полем правой. Подписи дополнительно
    прижимаются внутрь полосы методом label().
    """
    c = s.c
    data = [('2019', 1500, '>1 500'), ('2020', 1700, '>1 700'),
            ('2021', 1850, '>1 850'), ('2022', 2000, '>2 000'),
            ('2023', 3500, '>3 500'), ('2024', 4200, '>4 200'),
            ('2025', 4800, '>4 800')]
    x0, step = MARGIN_OUTER, 55.5*mm
    y0, h, vmax = 26*mm, 38*mm, 5000.0
    pts = [(x0 + i*step, y0 + h*(v/vmax)) for i, (_, v, _) in enumerate(data)]

    s.text('ДИНАМИКА РОСТА КОМПАНИИ', x0, BH - 18*mm, T.FONT_SEMI, T.MICRO,
           C.ORANGE, track=T.TRACK_CAPS)
    s.text('Объём работ в контрактах, млрд руб.', x0, BH - 25*mm,
           T.FONT_BOOK, T.SMALL, C.MUTED_D)

    # основание — линейка через сгиб: ось у двух полос одна
    s.rule(x0, y0, pts[-1][0] - x0 + 46*mm, C.LINE_D, 0.5)

    # Заливка под кривой — плотным тоном, а не прозрачностью: PDF/X-1a
    # живой прозрачности не допускает, а сведение её в печати даёт грязь.
    p = c.beginPath(); p.moveTo(pts[0][0], y0)
    for x, y in pts: p.lineTo(x, y)
    p.lineTo(pts[-1][0], y0); p.close()
    c.setFillColorRGB(*rgb((62, 66, 110)))
    c.drawPath(p, stroke=0, fill=1)

    c.setStrokeColorRGB(*rgb(C.ORANGE)); c.setLineWidth(1.6); c.setLineJoin(1)
    q = c.beginPath(); q.moveTo(*pts[0])
    for pt in pts[1:]: q.lineTo(*pt)
    c.drawPath(q, stroke=1, fill=0)

    for (x, y), (year, _, label) in zip(pts, data):
        c.setLineWidth(0.5); c.setStrokeColorRGB(*rgb(C.LINE_D))
        c.line(x, y0, x, y - 2.2*mm)
        c.setFillColorRGB(*rgb(C.ORANGE_HOT))
        c.circle(x, y, 1.9*mm, stroke=0, fill=1)
        s.label(label, x, y + 5*mm, T.FONT_BLACK, 13, C.WHITE, track=-6)
        s.label('млрд руб', x, y + 5*mm - 11, T.FONT_BOOK, T.MICRO, C.MUTED_D)
        s.label(year, x, y0 - 6*mm, T.FONT_MED, T.SMALL, C.MUTED_D, track=20)

    _, ox = edges(R)
    s.text('×3,2', ox, y0 + h*0.74, T.FONT_BLACK, 44, C.ORANGE, track=-14, align='r')
    s.lines(['рост портфеля', 'с 2019 года'], ox, y0 + h*0.74 - 9*mm,
            T.FONT_BOOK, T.SMALL, C.MUTED_D, T.LEAD_SMALL, align='r')


# ═════════════════════════ 6–7 · ЦИФРЫ | НАПРАВЛЕНИЯ РАБОТ ══════════════
def spread_06_07(s):
    """Единственный сплошной оранжевый разворот каталога.

    Цифры — сильнейший аргумент издания, и они должны быть видны с другого
    конца стола. Фирменный цвет здесь получает площадь, а не дозу в
    микрокегле надзаголовка; набор идёт глубоким фиолетовым.
    """
    t = base(s, 6, 'Компания в цифрах', 'Направления работ',
             ground='оранж', sag=6*mm)
    INK, MUT, LN = C.PURPLE_DEEP, (126, 88, 67), (176, 112, 60)

    # ── левая полоса: цифры ──────────────────────────────────────────────
    xl, wl = px(L, 0, 12)
    inner_l, _ = edges(L)
    s.eyebrow(L, 'ЧТО ПОСТРОЕНО', col=INK)
    # Кегль главной цифры подбирается под меру набора: 150 pt на семи знаках
    # ушли бы за наборную полосу на полсотни миллиметров.
    # 120 pt — потолок: выше метрический габарит строки налезает на
    # надзаголовок, хотя очко цифры до него не достаёт.
    hs = min(s.fit_size(['413 278'], wl, T.FONT_BLACK, T.HERO, track=-30), 120)
    s.text('413 278', xl, 214*mm, T.FONT_BLACK, hs, INK, track=-30)
    s.lines(['опор ЛЭП использовано', 'при строительстве'], xl, 193*mm,
            T.FONT_MED, T.H3, INK, T.LEAD_H2)

    rows = [('25 800 км', ['протянуто проводов на воздушных ЛЭП']),
            ('1 224',     ['ПС, ТП, РП построено объектов']),
            ('502 000',   ['объектов подключено к сетям']),
            ('339 км',    ['ГНБ прокол']),
            ('16 298 м²', ['построено и введено в эксплуатацию'])]
    ROW_Y, ROW_STEP = 162*mm, 30*mm
    y = ROW_Y
    for num, cap in rows:
        s.rule(xl, y + 11*mm, wl, LN, 0.6)
        s.text(num, xl, y, T.FONT_BLACK, 34, INK, track=-12)
        s.lines(cap, inner_l, y + 1*mm, T.FONT_BOOK, T.SMALL, MUT,
                T.LEAD_SMALL, align='r')
        y -= ROW_STEP
    s.rule(xl, y + 11*mm, wl, LN, 0.6)

    # ── правая полоса: направления ───────────────────────────────────────
    xr, wr = px(R, 0, 12)
    s.eyebrow(R, 'ЧТО МЫ ДЕЛАЕМ', col=INK)
    s.title(R, ['ПРОЕКТИРОВАНИЕ', 'И СТРОИТЕЛЬСТВО', 'В СФЕРЕ ЭНЕРГЕТИКИ'],
            size=30, dark=False)

    items = ['Внутренние электрические сети', 'Кабельные линии',
             'Воздушные линии электропередач',
             'Распределительные пункты, трансформаторные подстанции',
             'Архитектурное освещение',
             'Сервисное обслуживание электроустановок',
             'Электротехническая лаборатория', 'Наружное электроосвещение',
             'Пусконаладочные работы', 'ГНБ/ГНП']
    for i, it in enumerate(items):
        cx, cw = px(R, (i // 5)*6, 5)
        yy = ROW_Y - (i % 5)*ROW_STEP
        s.rule(cx, yy + 11*mm, cw, LN, 0.6)
        s.numbered(i + 1, cx, yy, it, size=11, num_w=11*mm, width=cw,
                   lead=1.38, num_col=INK, col=INK)
        if i % 5 == 4:
            s.rule(cx, yy - ROW_STEP + 11*mm, cw, LN, 0.6)


