def need_px(w150, h150):
    """Минимальный размер оригинала: слот в 300 dpi + запас на вылет/кроп."""
    return int(round(w150*2*1.08)), int(round(h150*2*1.08))

def main():
    os.makedirs('assets_needed/previews', exist_ok=True)
    rows=[]
    for (pg,key,desc,x0,y0,x1,y1,st) in SLOTS:
        img = cv2.imread(f'page_images_150dpi/pg{pg:02d}.jpg')
        crop = img[y0:min(y1,img.shape[0]), x0:min(x1,img.shape[1])]
        h,w = crop.shape[:2]
        # превью не шире 900 px
        sc = min(1.0, 900.0/w)
        cv2.imwrite(f'assets_needed/previews/{key}.jpg',
                    cv2.resize(crop,(int(w*sc),int(h*sc)),interpolation=cv2.INTER_AREA),
                    [int(cv2.IMWRITE_JPEG_QUALITY),86])
        nw,nh = need_px(w,h)
        rows.append(dict(page=pg,key=key,desc=desc,slot_px=f'{w}x{h}',
                         need_px=f'{nw}x{nh}',mpx=round(nw*nh/1e6,1),status=st))
    with open('assets_needed/list.csv','w',newline='',encoding='utf-8') as f:
        wr=csv.DictWriter(f,fieldnames=['page','key','desc','slot_px','need_px','mpx','status'])
        wr.writeheader(); wr.writerows(rows)
    json.dump(rows,open('assets_needed/list.json','w'),ensure_ascii=False,indent=1)
    req=[r for r in rows if r['status']=='REQ']
    sqz=[r for r in rows if r['status']=='SQZ']
    print(f'слотов всего: {len(rows)} | нет оригинала: {len(req)} | '
          f'есть пережатая копия: {len(sqz)} | готовых к печати: 0')
    for r in rows:
        print(f"стр{r['page']:>2} {r['status']:<4} {r['need_px']:>11} ({r['mpx']:>4} Мпикс)  {r['desc']}")

if __name__=='__main__': main()
