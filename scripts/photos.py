def page_raster(n):
    """Полоса n утверждённого каталога в её собственном растре 1240×1754."""
    pg = pymupdf.open(SRC)[n-1]
    z  = RW/pg.rect.width
    px = pg.get_pixmap(matrix=pymupdf.Matrix(z, z))
    a  = np.frombuffer(px.samples, np.uint8).reshape(px.height, px.width, px.n)
    return a[:, :, :3][:, :, ::-1]

def cut_all(verbose=True):
    os.makedirs(OUT, exist_ok=True)
    made = {}
    cache = {}
    for key, pg, x0, y0, x1, y1, desc in CLEAN:
        if pg not in cache:
            cache[pg] = page_raster(pg)
        crop = cache[pg][y0:y1, x0:x1]
        path = f'{OUT}/{key}.png'
        cv2.imwrite(path, crop)
        made[key] = path
        if verbose:
            h, w = crop.shape[:2]
            print(f'{key:20s} {w}×{h} px  →  до {w/300*25.4:5.1f}×{h/300*25.4:5.1f} мм '
                  f'в 300 dpi   {desc}')
    return made

def max_mm(path, dpi=300):
    """Предельный размер кадра на полосе при заданном разрешении печати."""
    a = cv2.imread(path)
    h, w = a.shape[:2]
    return w/dpi*25.4, h/dpi*25.4

def fit(path, w_mm, h_mm, dpi=300, anchor='c'):
    """Обрезать кадр «по заполнению» под пропорции прямоугольника и
    отмасштабировать ровно под нужное число пикселей.

    Лишних пикселей в PDF не остаётся: кадр кладётся в том размере, в каком
    печатается. Возвращает (массив, фактическое разрешение в dpi).
    """
    a = cv2.imread(path)
    h, w = a.shape[:2]
    want = w_mm/h_mm
    if w/h > want:                      # кадр шире рамки — режем бока
        nw = int(round(h*want))
        x = {'l': 0, 'c': (w-nw)//2, 'r': w-nw}[anchor]
        a = a[:, x:x+nw]
    else:                               # кадр выше рамки — режем верх/низ
        nh = int(round(w/want))
        y = {'t': 0, 'c': (h-nh)//2, 'b': h-nh}[anchor]
        a = a[y:y+nh]
    eff = a.shape[1]/(w_mm/25.4)        # фактическое разрешение до пересчёта
    tw = int(round(w_mm/25.4*dpi)); th = int(round(h_mm/25.4*dpi))
    if tw < a.shape[1]:                 # уменьшать можно, растягивать нельзя
        a = cv2.resize(a, (tw, th), interpolation=cv2.INTER_AREA)
    return a, eff

