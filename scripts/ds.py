# -*- coding: utf-8 -*-
"""
Дизайн-система каталога «ЭНЕРГО ГРУПП» — единственный источник правды.

Всё оформление полос берётся отсюда: ни одна полоса не задаёт свои цвета,
кегли и отступы. Иначе 32 полосы разъезжаются — ровно это и случилось с
прежней вёрсткой.

Единицы — пункты (pt), как в PDF. Полоса A4 210×297 мм.
"""
from reportlab.lib.units import mm

# ── Формат ───────────────────────────────────────────────────────────────
PAGE_W, PAGE_H = 210*mm, 297*mm
BLEED          = 4*mm          # вылет под обрез
SAFE           = 8*mm          # ничего важного ближе к обрезу

# ── Поля ─────────────────────────────────────────────────────────────────
# Корешковое поле крупнее внешнего: каталог сшивается, часть уходит в сгиб.
MARGIN_TOP     = 22*mm
MARGIN_BOTTOM  = 20*mm
MARGIN_OUTER   = 16*mm
MARGIN_INNER   = 22*mm

# ── Модульная сетка ──────────────────────────────────────────────────────
COLS      = 12
GUTTER    = 4*mm
BASELINE  = 4*mm               # вертикальный ритм, кратность отступов

def col_x(i, span=1, left_page=False):
    """Левый край и ширина блока на i-й колонке шириной span колонок.

    Координаты полосы (0…PAGE_W). Поля зеркальные: у левой полосы разворота
    крупное поле справа, у правой — слева, потому что корешок у них с разных
    сторон. Ширина наборной полосы при этом одинакова, 172 мм, — иначе
    соседние полосы разворота набраны разной мерой и разворот рассыпается.
    """
    ml = MARGIN_OUTER if left_page else MARGIN_INNER
    mr = MARGIN_INNER if left_page else MARGIN_OUTER
    content = PAGE_W - ml - mr
    cw = (content - GUTTER*(COLS-1))/COLS
    return ml + i*(cw+GUTTER), span*cw + (span-1)*GUTTER

# ── Разворот ─────────────────────────────────────────────────────────────
# Каталог сшивается и читается разворотами, поэтому единица вёрстки — не
# полоса, а разворот 420×297 мм. Полосы внутри него нумеруются 'L' и 'R',
# начало координат — левый нижний угол ОБРЕЗА ЛЕВОЙ полосы, ось x идёт через
# сгиб на правую полосу.
SPREAD_W = 2*PAGE_W
FOLD     = PAGE_W              # линия сгиба в координатах разворота
# Мёртвая зона сгиба: два корешковых поля. Внутрь не заходит ничего, что
# нужно прочитать или разглядеть, — в сшитом каталоге это дно воронки.
FOLD_DEAD = 2*MARGIN_INNER

def block(side):
    """Левый край и ширина наборной полосы полосы 'L' или 'R' разворота."""
    if side == 'L':
        return MARGIN_OUTER, PAGE_W - MARGIN_OUTER - MARGIN_INNER
    return PAGE_W + MARGIN_INNER, PAGE_W - MARGIN_INNER - MARGIN_OUTER

def px(side, i, span=1):
    """i-я колонка (span колонок) полосы side. Координаты разворота."""
    x0, w = block(side)
    cw = (w - GUTTER*(COLS-1))/COLS
    return x0 + i*(cw+GUTTER), span*cw + (span-1)*GUTTER

def edges(side):
    """(x у сгиба, x у внешнего обреза) наборной полосы — к ним прижимается
    набор: колонцифра к внешнему краю, перенос строки к внутреннему."""
    if side == 'L':
        return PAGE_W - MARGIN_INNER, MARGIN_OUTER
    return PAGE_W + MARGIN_INNER, SPREAD_W - MARGIN_OUTER

# Вертикальные опоры разворота. Надзаголовок и базовая линия заголовка
# одни и те же на всех разворотах каталога: иначе при листании шапка
# «дышит» вверх-вниз, и 32 полосы перестают выглядеть одним изданием.
Y_EYEBROW = PAGE_H - 34*mm
Y_TITLE   = PAGE_H - 56*mm

def across():
    """Левый край и ширина наборной полосы ВСЕГО разворота — для линеек,
    плашек и диаграмм, которые должны связать полосы в одно целое."""
    return MARGIN_OUTER, SPREAD_W - 2*MARGIN_OUTER

# ── Цвет ─────────────────────────────────────────────────────────────────
# Фирменные значения сняты с утверждённого каталога, не придуманы.
class C:
    ORANGE       = (224, 135,  47)   # основной акцент
    ORANGE_HOT   = (245, 140,  19)   # для мелких элементов, где нужен звон
    PURPLE_DEEP  = ( 46,  49,  84)   # фон полос — вместо прежнего градиента
    PURPLE       = ( 69,  75, 125)   # плашки, графика
    PURPLE_LIGHT = (120,  86, 133)   # нижний тон прежнего градиента, редко
    PAPER        = (242, 241, 238)   # светлые полосы
    WHITE        = (255, 255, 255)
    INK          = ( 26,  27,  38)   # текст на светлом
    MUTED_D      = (168, 172, 200)   # вторичный текст на тёмном
    MUTED_L      = (108, 112, 132)   # вторичный текст на светлом
