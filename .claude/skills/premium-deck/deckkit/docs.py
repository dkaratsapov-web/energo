          f'- 12 колонок, межколонник {ds["grid"]["gutter"]} мм, поля: боковые {ds["grid"]["margin"]} мм, '
          f'верх {ds["grid"]["top"]} мм, низ {ds["grid"]["bottom"]} мм.',
